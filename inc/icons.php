/**
 * Render an inline SVG icon.
 *
 * @param string $name  Icon key.
 * @param string $class Extra CSS classes.
 * @param int    $size  Pixel size for width/height attributes.
 * @return string
 */
function woodshop_icon( $name, $class = '', $size = 20 ) {
	$icons = woodshop_icons();

	if ( ! isset( $icons[ $name ] ) ) {
		return '';
	}

	return '<svg class="ws-icon ' . esc_attr( $class ) . '" width="' . (int) $size . '" height="' . (int) $size . '" aria-hidden="true" focusable="false" xmlns="http://www.w3.org/2000/svg"><use href="#ws-icon-' . esc_attr( $name ) . '"></use></svg>';
}

/**
 * Print the SVG sprite once per page.
 */
function woodshop_icon_sprite() {
	$icons = woodshop_icons();

	echo '<svg class="ws-icon-sprite" aria-hidden="true" focusable="false" xmlns="http://www.w3.org/2000/svg">';
	foreach ( $icons as $name => $icon ) {
		echo '<symbol id="ws-icon-' . esc_attr( $name ) . '" viewBox="' . esc_attr( $icon['view'] ) . '">';
		foreach ( $icon['paths'] as $path ) {
			echo '<path d="' . esc_attr( $path ) . '"></path>';
		}
		echo '</symbol>';
	}
	echo '</svg>';
}

